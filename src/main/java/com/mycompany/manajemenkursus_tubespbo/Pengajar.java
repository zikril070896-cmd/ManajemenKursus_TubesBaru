    private void Edit_btnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_Edit_btnActionPerformed
        List<String[]> list = DataMateri.bacaSemua();
        String[] m = list.get(selectedBab);
        String judulLama = m[0];

        String judulBaru = (String) JOptionPane.showInputDialog(
            this, "Edit Judul Materi:", "Edit",
            JOptionPane.PLAIN_MESSAGE, null, null, m[0]);
        if (judulBaru == null || judulBaru.trim().isEmpty()) return;

        String pengajarBaru = (String) JOptionPane.showInputDialog(
            this, "Nama Pengajar:", "Edit",
            JOptionPane.PLAIN_MESSAGE, null, null, m[1]);
        if (pengajarBaru == null) pengajarBaru = m[1];

        JTextArea ta = new JTextArea(m[2], 12, 45);
        ta.setLineWrap(true);
        ta.setWrapStyleWord(true);
        ta.setFont(new java.awt.Font("SansSerif", java.awt.Font.PLAIN, 13));

        int res = JOptionPane.showConfirmDialog(this, new JScrollPane(ta),
            "Edit Isi: " + judulBaru, JOptionPane.OK_CANCEL_OPTION);

        if (res == JOptionPane.OK_OPTION) {
            boolean ok = DataMateri.edit(judulLama, judulBaru.trim(),
                                         pengajarBaru.trim(), ta.getText().trim());
            if (ok) {
                muatLabelBab();
                JOptionPane.showMessageDialog(this, "Materi berhasil diperbarui!");
            }
        }// TODO add your handling code here:
    }//GEN-LAST:event_Edit_btnActionPerformed

    private void Tmbh_btnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_Tmbh_btnActionPerformed
        if (DataMateri.jumlah() >= 3) {
            JOptionPane.showMessageDialog(this,
                "Maksimal 3 bab. Hapus salah satu terlebih dahulu.");
            return;
        }

        String judul = JOptionPane.showInputDialog(this, "Judul Materi Baru:");
        if (judul == null || judul.trim().isEmpty()) return;

        String pengajar = JOptionPane.showInputDialog(this, "Nama Pengajar:");
        if (pengajar == null) pengajar = "";

        JTextArea ta = new JTextArea("", 12, 45);
        ta.setLineWrap(true);
        ta.setWrapStyleWord(true);
        ta.setFont(new java.awt.Font("SansSerif", java.awt.Font.PLAIN, 13));

        int res = JOptionPane.showConfirmDialog(this, new JScrollPane(ta),
            "Tulis Isi: " + judul, JOptionPane.OK_CANCEL_OPTION);

        if (res == JOptionPane.OK_OPTION) {
            boolean ok = DataMateri.tambah(judul.trim(), pengajar.trim(), ta.getText().trim());
            if (ok) {
                muatLabelBab();
                JOptionPane.showMessageDialog(this, "Materi berhasil ditambahkan!");
            }
        }// TODO add your handling code here:
    }//GEN-LAST:event_Tmbh_btnActionPerformed

    private void Hps_btnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_Hps_btnActionPerformed
        int konfirmasi = JOptionPane.showConfirmDialog(this,
            "Yakin hapus \"" + selectedJudul + "\"?",
            "Konfirmasi Hapus", JOptionPane.YES_NO_OPTION);

        if (konfirmasi == JOptionPane.YES_OPTION) {
            boolean ok = DataMateri.hapus(selectedJudul);
            if (ok) {
                muatLabelBab();
                JOptionPane.showMessageDialog(this, "Materi berhasil dihapus!");
            }
        }// TODO add your handling code here:
    }//GEN-LAST:event_Hps_btnActionPerformed

