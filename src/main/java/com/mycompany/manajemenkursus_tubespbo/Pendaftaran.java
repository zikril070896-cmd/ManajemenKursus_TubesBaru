    private void Simpan_btnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_Simpan_btnActionPerformed
        
    String tanggal = TglDaftar_btn.getText().trim();
    String status = Status_btn.getText().trim();
    String email = Email_btn.getText().trim();
    String alamat = Alamat_btn.getText().trim();

    if(tanggal.isEmpty() || status.isEmpty() || email.isEmpty() || alamat.isEmpty()){
        javax.swing.JOptionPane.showMessageDialog(this,
                "Semua data harus diisi!");
        return;
    }

    try(Connection conn = Koneksi.getConnection()){

        String sql = "INSERT INTO pendaftaran "
                + "(Tanggal_Pendaftaran, Status, Email, Alamat)"
                + " VALUES (?,?,?,?)";

        PreparedStatement ps = conn.prepareStatement(sql);

        ps.setString(1,tanggal);
        ps.setString(2,status);
        ps.setString(3,email);
        ps.setString(4,alamat);

        ps.executeUpdate();

        javax.swing.JOptionPane.showMessageDialog(this,
                "Data berhasil disimpan!");

        loadData();
        clearField();

    }catch(SQLException e){
        javax.swing.JOptionPane.showMessageDialog(this,
                e.getMessage());
    }// TODO add your handling code here:
    }//GEN-LAST:event_Simpan_btnActionPerformed

