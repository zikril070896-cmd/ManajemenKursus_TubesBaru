    private void Edit_btnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_Edit_btnActionPerformed
    String id = IdDaftar_btn.getText().trim();
    String tanggal = TglDaftar_btn.getText().trim();
    String status = Status_btn.getText().trim();
    String email = Email_btn.getText().trim();
    String alamat = Alamat_btn.getText().trim();

    try(Connection conn = Koneksi.getConnection()){

        String sql="UPDATE pendaftaran SET "
                + "Tanggal_Pendaftaran=?,"
                + "Status=?,"
                + "Email=?,"
                + "Alamat=? "
                + "WHERE idPendaftaran=?";

        PreparedStatement ps=conn.prepareStatement(sql);

        ps.setString(1,tanggal);
        ps.setString(2,status);
        ps.setString(3,email);
        ps.setString(4,alamat);
        ps.setString(5,id);

        ps.executeUpdate();

        javax.swing.JOptionPane.showMessageDialog(this,
                "Data berhasil diubah!");

        loadData();
        clearField();

    }catch(SQLException e){
        javax.swing.JOptionPane.showMessageDialog(this,
                e.getMessage());
    }// TODO add your handling code here:
    }//GEN-LAST:event_Edit_btnActionPerformed

    private void Hapus_btnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_Hapus_btnActionPerformed
        String id = IdDaftar_btn.getText().trim();

    int pilih = javax.swing.JOptionPane.showConfirmDialog(
            this,
            "Yakin ingin menghapus data?",
            "Konfirmasi",
            javax.swing.JOptionPane.YES_NO_OPTION);

    if(pilih==javax.swing.JOptionPane.YES_OPTION){

        try(Connection conn=Koneksi.getConnection()){

            String sql="DELETE FROM pendaftaran "
                    + "WHERE idPendaftaran=?";

            PreparedStatement ps=conn.prepareStatement(sql);

            ps.setString(1,id);

            ps.executeUpdate();

            javax.swing.JOptionPane.showMessageDialog(this,
                    "Data berhasil dihapus!");

            loadData();
            clearField();

        }catch(SQLException e){
            javax.swing.JOptionPane.showMessageDialog(this,
                    e.getMessage());
        }

    }// TODO add your handling code here:
    }//GEN-LAST:event_Hapus_btnActionPerformed

