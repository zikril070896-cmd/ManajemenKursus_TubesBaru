private void loadData() {
    tableModel.setRowCount(0);
    try (java.sql.Connection conn = Koneksi.getConnection()) {
        String sql = "SELECT total_bayar, metode_bayar, bukti, no_rekening FROM transaksi";
        java.sql.PreparedStatement ps = conn.prepareStatement(sql);
        java.sql.ResultSet rs = ps.executeQuery();
        while (rs.next()) {
            tableModel.addRow(new Object[]{
                rs.getString("total_bayar"),
                rs.getString("metode_bayar"),
                rs.getString("bukti"),
                rs.getString("no_rekening")
            });
        }
    }   
        catch (java.sql.SQLException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Gagal load data: " + e.getMessage());
        }
}
