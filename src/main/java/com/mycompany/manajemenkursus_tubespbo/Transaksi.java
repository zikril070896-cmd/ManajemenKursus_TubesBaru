    private void Edit_btnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_Edit_btnActionPerformed
        int row = Transaksi_tabel.getSelectedRow();
        if (row == -1) {
            javax.swing.JOptionPane.showMessageDialog(this, "Pilih baris yang ingin diedit!");
            return;
        }

        String total  = Totalbyr_field.getText().trim();
        String metode = Metodebyr_field.getText().trim();
        String bukti  = Bukti_field.getText().trim();
        String norek  = Norek_field.getText().trim();

        if (total.isEmpty() || metode.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Total dan Metode Bayar wajib diisi!");
            return;
        }

        String oldTotal = tableModel.getValueAt(row, 0).toString();
        String oldNorek = tableModel.getValueAt(row, 3) != null ? tableModel.getValueAt(row, 3).toString() : "";

        try (Connection conn = Koneksi.getConnection()) {
            String sql = "UPDATE transaksi SET total_bayar=?, metode_bayar=?, bukti=?, no_rekening=? WHERE total_bayar=? AND no_rekening=?";
            PreparedStatement ps = conn.prepareStatement(sql);
            ps.setString(1, total);
            ps.setString(2, metode);
            ps.setString(3, bukti);
            ps.setString(4, norek);
            ps.setString(5, oldTotal);
            ps.setString(6, oldNorek);
            ps.executeUpdate();
            javax.swing.JOptionPane.showMessageDialog(this, "Data berhasil diupdate!");
            loadData();
            clearFields();
        } catch (SQLException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Gagal edit: " + e.getMessage());
        }// TODO add your handling code here:
    }//GEN-LAST:event_Edit_btnActionPerformed

    private void Hapus_btnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_Hapus_btnActionPerformed
        int row = Transaksi_tabel.getSelectedRow();
        if (row == -1) {
            javax.swing.JOptionPane.showMessageDialog(this, "Pilih baris yang ingin dihapus!");
            return;
        }

        int confirm = javax.swing.JOptionPane.showConfirmDialog(this,
            "Yakin ingin menghapus data ini?", "Konfirmasi",
            javax.swing.JOptionPane.YES_NO_OPTION);

        if (confirm == javax.swing.JOptionPane.YES_OPTION) {
            String oldTotal = tableModel.getValueAt(row, 0).toString();
            String oldNorek = tableModel.getValueAt(row, 3) != null ? tableModel.getValueAt(row, 3).toString() : "";

            try (Connection conn = Koneksi.getConnection()) {
                String sql = "DELETE FROM transaksi WHERE total_bayar=? AND no_rekening=?";
                PreparedStatement ps = conn.prepareStatement(sql);
                ps.setString(1, oldTotal);
                ps.setString(2, oldNorek);
                ps.executeUpdate();
                javax.swing.JOptionPane.showMessageDialog(this, "Data berhasil dihapus!");
                loadData();
                clearFields();
            } catch (SQLException e) {
                javax.swing.JOptionPane.showMessageDialog(this, "Gagal hapus: " + e.getMessage());
            }
        }// TODO add your handling code here:
    }//GEN-LAST:event_Hapus_btnActionPerformed

